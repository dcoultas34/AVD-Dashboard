# =============================================================================
# session-history.ps1  -  Additional LAW-sourced data for session hosts
# Author  : virtualwebber (https://github.com/virtualwebber/AVD-Dashboard)
# =============================================================================
# Dot-sourced by session-detail.ps1. Provides Show-SessionHistory which opens
# a modal window querying Log Analytics for additional user session detail.
# Queries are user-centric: users are extracted from the parent session detail
# DataTable and events are found across ALL session hosts (not just the host
# the user is currently on). Each timestamp cell shows the device it occurred on.
# Data is queried from LAW only when the window is opened, then auto-refreshes
# at the same interval as the main dashboard ($script:RefreshIntervalSeconds).
# Logging writes to $script:LogFile (shared with the main dashboard).
#
# DATA SOURCES & REQUIREMENTS:
#
#   1. Lock/Unlock Events (Security Event Log)
#      EventID 4800 = Workstation Locked, 4801 = Workstation Unlocked
#      Requires the following audit policy on each session host:
#
#        Computer Configuration > Windows Settings > Security Settings >
#          Advanced Audit Policy Configuration > Logon/Logoff >
#            Audit Other Logon/Logoff Events = Success
#
#      Deploy via Group Policy (recommended) or local security policy.
#      The Security event log must be collected to the configured LAW.
#
#   2. Session Lifecycle Events (TerminalServices-LocalSessionManager)
#      EventID 21 = Logon, 23 = Logoff, 24 = Disconnect, 25 = Reconnect
#      Source: Microsoft-Windows-TerminalServices-LocalSessionManager/Operational
#      This log is generated by default on Windows; no audit policy change needed.
#      However, the log must be collected to the configured LAW via Azure Monitor
#      Agent (AMA) Data Collection Rules or the legacy Microsoft Monitoring Agent.
#
#   3. Disconnect Reason Codes (TerminalServices-LocalSessionManager EventID 40)
#      EventID 40 fires alongside EventID 24 (Disconnect) and contains a reason
#      code in RenderedDescription: "Session X has been disconnected, reason code Y"
#      This is joined to EventID 24 via SessionHost + SessionID (within a 10-second
#      time window) to classify each disconnect. Reason code mapping:
#        0  = Normal           (default/TCP close - includes client power-off)
#        1  = User Initiated   (user chose to disconnect)
#        2  = Admin Initiated  (admin forced disconnect)
#        5  = Session Replaced (user logged in elsewhere, replacing this session)
#        11 = Idle Timeout     (session timed out due to inactivity)
#        12 = Logoff           (user logged off gracefully)
#        28 = Session Ended    (undocumented - observed in AVD environments)
#      Note: Reason codes are from the session host's perspective. A client crash
#      or power-off appears as code 0 (Normal) because the host only sees a TCP
#      connection closure, not why the client disappeared. EventID 40 does NOT
#      contain a User field, so it must be correlated with EventID 24 which does.
#
#   Without the relevant logs collected to LAW, the corresponding columns in the
#   Session History grid will show no results ("-").
# =============================================================================

# -----------------------------------------------------------------------------
# _AdvRefreshData - Queries LAW for lock/unlock and session lifecycle summary
# -----------------------------------------------------------------------------
# Called on initial load, by the auto-refresh timer, and by the Refresh Now
# button. Extracts unique users from the parent session detail DataTable,
# queries the LAW Event table for both Security lock/unlock events and
# TerminalServices session lifecycle events across ALL hosts, then merges
# the results into a single summary grid (one row per user per session host).
#
# A single combined KQL query fetches both lock/unlock (Security 4800/4801) and
# session lifecycle (TerminalServices 21/23/24/25 + EventID 40 disconnect reasons)
# data in one REST call. The KQL uses "let" statements for each sub-query and a
# fullouter join to merge them, so rows appear even if a user has only lock data
# or only session data. This halves the network wait vs two sequential REST calls.
# -----------------------------------------------------------------------------
function script:_AdvRefreshData {
    # Show status immediately so the user knows a query is in progress
    $script:_advStatus.Text = "Querying Log Analytics..."

    # Force WPF to render the status text before the blocking REST call.
    # Without this, the status label update would be queued but not painted
    # until after the REST call returns, so the user would see no visual
    # feedback. The DispatcherFrame trick pushes all pending render operations
    # (including the label update) through the message pump, then returns
    # control so we can proceed with the blocking HTTP call.
    try {
        $frame = New-Object System.Windows.Threading.DispatcherFrame
        [System.Windows.Threading.Dispatcher]::CurrentDispatcher.BeginInvoke(
            [System.Windows.Threading.DispatcherPriority]::Background,
            [System.Threading.ThreadStart]{ $frame.Continue = $false }
        )
        [System.Windows.Threading.Dispatcher]::PushFrame($frame)
    } catch {}

    try {
        $lawId = $script:LawWorkspaceResourceId

        # --- Build user filter for the KQL query ---
        # Two modes:
        #   1. Normal mode: extract unique usernames from the parent session detail
        #      DataTable and build a KQL "let users = dynamic([...]);" filter so the
        #      query only returns data for users who have active sessions. This keeps
        #      results focused and reduces LAW query cost.
        #   2. "Query All Users" mode ($script:_shQueryAllUsers = $true): skip the
        #      filter entirely, returning lock/session data for ALL users in the
        #      last 12 hours. Useful for investigating users who may have logged off
        #      but still have recent lock/session events.
        #
        # The filter is injected into the KQL via three variables:
        #   $userFilter       - "let users = dynamic([...]);" or empty string
        #   $lockUserWhere    - "| where tolower(TargetUser) in (users)" or empty
        #   $sessionUserWhere - "| where tolower(SessionUser) in (users)" or empty
        # When empty, the KQL simply has no user filter and returns all data.
        $userFilter = ''
        $lockUserWhere = ''
        $sessionUserWhere = ''
        if (-not $script:_shQueryAllUsers) {
            # Extract usernames from the parent session detail DataTable.
            # Usernames may be in DOMAIN\user or user@domain format - we strip
            # the domain part to get just the sAMAccountName for KQL matching.
            $users = @($script:sdDataTable.Rows | ForEach-Object {
                $u = [string]$_['User']
                if ($u -match '\\') { $u = $u.Split('\')[-1] }
                elseif ($u -match '@') { $u = $u.Split('@')[0] }
                $u
            } | Where-Object { $_ -and $_ -ne '-' -and $_ -ne '' } | Select-Object -Unique)

            if ($users.Count -eq 0) {
                $script:_advStatus.Text = "No active users found."
                if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] No active users found`r`n") } catch {} }
                return
            }

            if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] Querying for $($users.Count) user(s): $($users -join ', ')`r`n") } catch {} }
            # Build a KQL dynamic array of lowercase usernames for the "in" operator.
            # Example output: let users = dynamic(['alice','bob']);
            # The lock sub-query filters on TargetUser (Security log field),
            # the session sub-query filters on SessionUser (TerminalServices field).
            $userList = @($users | ForEach-Object { "'$($_.ToLower())'" }) -join ','
            $userFilter = "let users = dynamic([$userList]);`n"
            $lockUserWhere = '| where tolower(TargetUser) in (users)'
            $sessionUserWhere = '| where tolower(SessionUser) in (users)'
        } else {
            if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] Querying ALL users`r`n") } catch {} }
        }

        # ----- Combined KQL: Lock/Unlock + Session Lifecycle in a single query -----
        #
        # ARCHITECTURE: Instead of making two sequential REST calls to LAW (one for
        # lock/unlock, one for session lifecycle), we use KQL "let" statements to
        # define both sub-queries within a single KQL string. LAW executes all the
        # sub-queries server-side and returns a single unified result set. This
        # eliminates one full HTTP round-trip (typically ~1-5 seconds of network
        # latency per call), cutting the total wait time roughly in half.
        #
        # KQL "let" STRUCTURE (6 steps):
        #
        #   1. "lockData" - Queries the Security event log for EventIDs 4800 (Lock)
        #      and 4801 (Unlock). Parses TargetUserName from XML EventData, filters
        #      out machine accounts (ending in $), and summarizes the most recent
        #      lock/unlock timestamp per user per session host. Derives LockState
        #      by comparing which timestamp is more recent.
        #
        #   2. "ev" - Queries the TerminalServices-LocalSessionManager/Operational
        #      event log for EventIDs 21 (Logon), 23 (Logoff), 24 (Disconnect),
        #      25 (Reconnect). Parses User and SessionID from XML EventData.
        #      Strips domain prefix (DOMAIN\user -> user).
        #
        #   3. "reasons" - Queries EventID 40 from the same log. EventID 40 fires
        #      alongside EventID 24 and contains a disconnect reason code in its
        #      RenderedDescription text (e.g., "Session 3 has been disconnected,
        #      reason code 11"). Parses out the SessionID and ReasonCode.
        #
        #   4. "lastDiscReason" - Joins EventID 24 rows from "ev" with EventID 40
        #      rows from "reasons" via matching SessionHost + SessionID, within a
        #      10-second time window. This correlation is needed because EventID 40
        #      does NOT contain a User field - it only has SessionID. The 10-second
        #      window handles slight timestamp differences between the two events.
        #      Takes the most recent disconnect reason per user per host.
        #
        #   5. "sessionData" - Summarizes the most recent timestamp for each lifecycle
        #      event type (Logon/Logoff/Disconnect/Reconnect) per user per host, then
        #      left-joins with "lastDiscReason" to attach the disconnect reason code.
        #
        #   6. FINAL: fullouter join of "lockData" + "sessionData" on User + SessionHost.
        #      fullouter ensures rows appear even if a user has ONLY lock data or ONLY
        #      session data. The coalesce() calls resolve duplicate column names from
        #      the join (KQL auto-suffixes the right-side duplicates with "1", so
        #      coalesce(User, User1) picks whichever side has data).
        #
        # NOTE on backtick escaping: The KQL uses `$left.SessId == `$right.SessId40
        # for the join condition. In a PowerShell double-quoted here-string (@"..."@),
        # $ is interpolated, so we escape with backtick (`) to pass literal $ to KQL.
        #
        # ── Lock State intelligence (applied after the fullouter join at the end of the KQL) ──
        # The raw LockState from lockData is based purely on which event (4800=lock vs
        # 4801=unlock) happened most recently. This is misleading in several scenarios:
        #   1. User logged off/disconnected after the lock - session is gone, lock state
        #      is stale and should show "-".
        #   2. User logged off then logged back on - the lock from the OLD session should
        #      not carry over to the new session. E.g. lock at 17:42, logoff at 18:00,
        #      new logon at 20:40 - the lock is from a previous session and irrelevant.
        # Three checks clear stale lock states after the join:
        #   Check 1: No lock data at all -> "-"
        #   Check 2: Session not active (last logoff/disconnect after last logon/reconnect) -> "-"
        #   Check 3: Lock event predates the current session start (from a previous session) -> "-"
        # Build date range from the DatePicker selection (defaults to today)
        $selDate = if ($script:_advDatePicker -and $script:_advDatePicker.SelectedDate) {
            $script:_advDatePicker.SelectedDate
        } else { [DateTime]::Today }
        $dateStart = $selDate.ToString('yyyy-MM-dd') + 'T00:00:00Z'
        $dateEnd   = $selDate.ToString('yyyy-MM-dd') + 'T23:59:59Z'

        $kql = @"
${userFilter}let lockData = Event
| where TimeGenerated between (datetime($dateStart) .. datetime($dateEnd))
| where EventLog == "Security" and EventID in (4800, 4801)
| parse EventData with * '<Data Name="TargetUserName">' TargetUser '</Data>' *
| where TargetUser != "" and TargetUser !endswith "$"
${lockUserWhere}
| extend SessionHost = tolower(split(Computer, '.')[0])
| summarize
    LastLock   = maxif(TimeGenerated, EventID == 4800),
    LastUnlock = maxif(TimeGenerated, EventID == 4801)
    by TargetUser, SessionHost
| extend LockState = case(
    isempty(LastLock) and isempty(LastUnlock), "-",
    LastLock > LastUnlock or isempty(LastUnlock), "Locked",
    "Unlocked")
| project User=TargetUser, SessionHost, LastLock, LastUnlock, LockState;
let ev = Event
| where TimeGenerated between (datetime($dateStart) .. datetime($dateEnd))
| where EventLog == "Microsoft-Windows-TerminalServices-LocalSessionManager/Operational"
      and EventID in (21, 23, 24, 25)
| parse EventData with * '<User>' SessionUser '</User>' *
| parse EventData with * '<SessionID>' SessId '</SessionID>' *
| where SessionUser != ""
| extend SessionUser = iff(SessionUser contains "\\",
           tostring(split(SessionUser, "\\")[1]), SessionUser)
| where SessionUser !endswith "$"
${sessionUserWhere}
| extend SessionHost = tolower(split(Computer, '.')[0]);
let reasons = Event
| where TimeGenerated between (datetime($dateStart) .. datetime($dateEnd))
| where EventLog == "Microsoft-Windows-TerminalServices-LocalSessionManager/Operational"
      and EventID == 40
| parse RenderedDescription with "Session " SessId40 " has been disconnected, reason code " ReasonCode
| extend SessionHost = tolower(split(Computer, '.')[0]);
let lastDiscReason = ev
| where EventID == 24
| join kind=leftouter reasons on SessionHost, `$left.SessId == `$right.SessId40
| where isnull(TimeGenerated1) or abs(datetime_diff('second', TimeGenerated, TimeGenerated1)) < 10
| summarize arg_max(TimeGenerated, ReasonCode) by SessionUser, SessionHost;
let sessionData = ev
| summarize
    LastLogon      = maxif(TimeGenerated, EventID == 21),
    LastLogoff     = maxif(TimeGenerated, EventID == 23),
    LastDisconnect = maxif(TimeGenerated, EventID == 24),
    LastReconnect  = maxif(TimeGenerated, EventID == 25)
    by SessionUser, SessionHost
| join kind=leftouter lastDiscReason on SessionUser, SessionHost
| project User=SessionUser, SessionHost, LastLogon, LastLogoff, LastDisconnect, LastReconnect, DisconnectReason=coalesce(ReasonCode, "");
lockData
| join kind=fullouter sessionData on User, SessionHost
| extend User=coalesce(User, User1), SessionHost=coalesce(SessionHost, SessionHost1)
| extend LastSessionStart = max_of(
    iff(isnotempty(LastLogon), LastLogon, datetime(null)),
    iff(isnotempty(LastReconnect), LastReconnect, datetime(null)))
| extend LastSessionEnd = max_of(
    iff(isnotempty(LastLogoff), LastLogoff, datetime(null)),
    iff(isnotempty(LastDisconnect), LastDisconnect, datetime(null)))
| extend SessionActive = isnotempty(LastSessionStart) and
    (isempty(LastSessionEnd) or LastSessionStart > LastSessionEnd)
| extend LastLockEvent = max_of(
    iff(isnotempty(LastLock), LastLock, datetime(null)),
    iff(isnotempty(LastUnlock), LastUnlock, datetime(null)))
| extend LockState = case(
    LockState == "-" or isempty(LockState), "-",
    not(SessionActive), "-",
    isnotempty(LastSessionStart) and isnotempty(LastLockEvent) and LastLockEvent < LastSessionStart, "-",
    LockState)
| project User, SessionHost,
          LastLock, LastUnlock, LockState, LastLogon, LastLogoff, LastDisconnect, LastReconnect, DisconnectReason
| order by User asc, SessionHost asc
"@

        # --- Execute the single combined query via ARM REST API ---
        # POST to the LAW query endpoint. The timespan parameter limits the query
        # window to 12 hours (matching the ago(12h) in the KQL itself). The
        # -FullResponse flag returns the raw LAW response object (with .tables[],
        # .columns[], .rows[]) instead of just the flattened results.
        $sw = $null; if ($script:LogFile) { $sw = [System.Diagnostics.Stopwatch]::StartNew() }

        # P30D timespan covers the full 30-day range the DatePicker allows;
        # the KQL 'between' clause narrows results to the selected day only.
        $resp = Invoke-LawQuery -Kql $kql -Timespan 'P30D' `
            -WorkspaceResourceId $lawId -QueryBaseUrl $script:LawQueryBaseUrl
        if ($sw) { $sw.Stop() }

        # -----------------------------------------------------------------------
        # Unique User Stats Query - Summary Tiles (24h and 7d)
        # -----------------------------------------------------------------------
        # Purpose: Populates the two summary tiles at the top of the Session
        # History window (ShStatUsers24h / ShStatUsers7d) with a count of how
        # many distinct users had any session activity in each time window.
        #
        # This is a SEPARATE, lightweight KQL query from the main grid query
        # above. It intentionally does NOT apply the current user filter (i.e.
        # it is not restricted to users visible in the parent Session Detail
        # window). The tiles answer the question "how many unique users were
        # active across the whole environment?" rather than just the current
        # session detail view.
        #
        # HOW UNIQUE USERS ARE COUNTED:
        #   1. Only TerminalServices-LocalSessionManager EventID 21 (Logon) is
        #      queried. This counts users who started a new session (fresh logon
        #      or reconnect to a new session) within the window. Logoff (23),
        #      Disconnect (24), and Reconnect (25) are deliberately excluded so
        #      that users with old long-running sessions are not inflating the
        #      count just because they disconnected or reconnected.
        #   2. The <User> field is extracted from each event's XML EventData.
        #   3. The domain prefix is stripped (DOMAIN\user -> user) and the
        #      result is lowercased so CFSI\AWebber01 and CFSI\awebber01 both
        #      resolve to the same user (awebber01).
        #   4. Machine accounts (usernames ending in $) are excluded.
        #   5. KQL dcount(ShortUser) counts distinct usernames for each window:
        #        - u24h: users who logged on at least once in the last 24 hours
        #        - u7d:  users who logged on at least once in the last 7 days
        #   6. The two counts are unioned into a two-row result set with a
        #      Period column ("24h" or "7d") and a Count column.
        #
        # A user who logged on 3 times counts as 1 unique user, not 3.
        # The 7d count will always be >= the 24h count.
        #
        # The timespan parameter is set to P7D (7 days) to match the longest
        # ago() window in the KQL. Without this, LAW may reject the query or
        # return partial data for the 7d window.
        #
        # Errors (e.g. LAW not configured, permission denied) are silently
        # swallowed - the tiles simply retain their default "-" value.
        # -----------------------------------------------------------------------
        try {
            $statsKql = @'
let ev = Event
| where EventLog == "Microsoft-Windows-TerminalServices-LocalSessionManager/Operational"
| where EventID == 21
| parse EventData with * '<User>' u '</User>' *
| where isnotempty(u) and u !endswith "$"
| extend ShortUser = tolower(iff(u contains "\\", tostring(split(u, "\\")[1]), u));
let u24h = ev | where TimeGenerated > ago(24h) | summarize dcount(ShortUser);
let u7d  = ev | where TimeGenerated > ago(7d)  | summarize dcount(ShortUser);
union (u24h | extend Period="24h"), (u7d | extend Period="7d")
| project Period, Count=dcount_ShortUser
'@
            $statsResp = Invoke-LawQuery -Kql $statsKql -Timespan 'P7D' `
                -WorkspaceResourceId $lawId -QueryBaseUrl $script:LawQueryBaseUrl

            # Parse the two-row result and update the TextBlock tiles on screen.
            # Row[0] is Period ("24h" or "7d"), Row[1] is the dcount integer.
            # Guard with null check in case the window was closed between the
            # REST call starting and this code running.
            if ($statsResp.tables -and $statsResp.tables[0].rows) {
                foreach ($r in $statsResp.tables[0].rows) {
                    if ($r[0] -eq '24h' -and $script:_shStatUsers24h) { $script:_shStatUsers24h.Text = [string]$r[1] }
                    if ($r[0] -eq '7d'  -and $script:_shStatUsers7d)  { $script:_shStatUsers7d.Text  = [string]$r[1] }
                }
            }
        } catch {
            # Non-fatal: stats tiles remain at "-" if this query fails.
            # The main grid query result is unaffected.
        }

        # Log the query timing and row count for diagnostics.
        # Typical times: ~1s cold (first query), ~150ms cached (subsequent queries).
        $rowCount = if ($resp.tables -and $resp.tables[0].rows) { $resp.tables[0].rows.Count } else { 0 }
        if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] Combined query: $rowCount row(s) ($($sw.ElapsedMilliseconds)ms)`r`n") } catch {} }

        if ($rowCount -gt 0) {
            # --- Build a WPF-bindable DataTable from the LAW response ---
            # The DataTable has 11 columns in display order. State columns are first
            # for quick visual scanning, followed by chronological timestamp columns.
            # One row = one user on one session host.
            $dt = New-Object System.Data.DataTable
            [void]$dt.Columns.Add("User")
            [void]$dt.Columns.Add("Session Host")
            [void]$dt.Columns.Add("Lock State")
            [void]$dt.Columns.Add("Session State")
            [void]$dt.Columns.Add("Last Lock")
            [void]$dt.Columns.Add("Last Unlock")
            [void]$dt.Columns.Add("Last Logon")
            [void]$dt.Columns.Add("Last Logoff")
            [void]$dt.Columns.Add("Last Disconnect")
            [void]$dt.Columns.Add("Disconnect Type")
            [void]$dt.Columns.Add("Last Reconnect")

            # Helper to find a column's index by name in a LAW response.
            # LAW response column objects have different property names depending
            # on the PowerShell version and Az module version:
            #   - .name       (newer Az modules / PS7)
            #   - .ColumnName (older PS5.1 with some module versions)
            #   - [string]$_  (fallback - treats the object itself as a string)
            # The fallback chain ensures compatibility across all versions.
            # Returns -1 if the column is not found (caller must check >= 0).
            $findCol = {
                param($resp, $name)
                $c = @($resp.tables[0].columns | ForEach-Object {
                    $n = [string]$_.name; if (-not $n) { $n = [string]$_.ColumnName }; if (-not $n) { $n = [string]$_ }; $n.ToLower()
                })
                [array]::IndexOf($c, $name.ToLower())
            }

            # Helper to format a UTC timestamp from the LAW response to a local
            # display string. LAW always returns timestamps in UTC ISO 8601 format.
            # We convert to the user's local timezone for display. Returns '-' if
            # the timestamp is null/empty (meaning no event of that type was found).
            $fmtTime = {
                param($row, $timeIdx)
                $ts = if ($timeIdx -ge 0 -and $row[$timeIdx]) { [string]$row[$timeIdx] } else { '' }
                if ($ts -and $ts -ne '') {
                    try { return ([DateTime]::Parse($ts)).ToLocalTime().ToString("yyyy-MM-dd HH:mm:ss") } catch { return $ts }
                }
                return '-'
            }

            # Disconnect reason code mapping (EventID 40 reason codes)
            # Maps numeric reason codes from RenderedDescription to human-readable
            # labels. Codes are from the session host perspective - a client crash
            # or power-off appears as code 0 (Normal) because the host only sees
            # the TCP connection close, not the reason behind it.
            # See file header comment "3. Disconnect Reason Codes" for full details.
            $reasonMap = @{
                '0'  = 'Normal'
                '1'  = 'User Initiated'
                '2'  = 'Admin Initiated'
                '5'  = 'Session Replaced'
                '11' = 'Idle Timeout'
                '12' = 'Logoff'
                '28' = 'Session Ended (28)'
            }
            # Scriptblock to resolve a reason code string to its label.
            # Returns '-' if no code is present (no disconnect event found),
            # or "Unknown (code)" for any unrecognised code not in the map.
            $mapReason = {
                param($code)
                $c = [string]$code
                if (-not $c -or $c -eq '') { return '-' }
                if ($reasonMap.ContainsKey($c)) { return $reasonMap[$c] }
                return "Unknown ($c)"
            }

            # --- Resolve column indices from the combined LAW response ---
            # The fullouter join returns exactly 10 columns in a single result set.
            # We look up each column by name (case-insensitive) rather than hardcoding
            # ordinal positions, in case LAW ever reorders them or KQL changes.
            # Columns: User, SessionHost, LastLock, LastUnlock, LockState,
            #          LastLogon, LastLogoff, LastDisconnect, LastReconnect, DisconnectReason
            $iUser    = & $findCol $resp 'user'
            $iHost    = & $findCol $resp 'sessionhost'
            $iLock    = & $findCol $resp 'lastlock'
            $iUnlck   = & $findCol $resp 'lastunlock'
            $iLS      = & $findCol $resp 'lockstate'
            $iLogon   = & $findCol $resp 'lastlogon'
            $iLogoff  = & $findCol $resp 'lastlogoff'
            $iDisc    = & $findCol $resp 'lastdisconnect'
            $iRecon   = & $findCol $resp 'lastreconnect'
            $iDReason = & $findCol $resp 'disconnectreason'

            # --- Build session state lookup from the parent session detail DataTable ---
            # The "Session State" column (Active/Disconnected/etc.) is NOT available
            # in LAW event logs - it comes from the live AVD management API in the
            # parent session detail window. We build a hashtable keyed by
            # "username|hostname" (both lowercased) to look up the current live state
            # for each user/host combination. Users not found in the parent DataTable
            # (e.g., users who logged off and only appear in LAW history) show
            # "No Session" instead. Domain prefixes are stripped to match the LAW
            # username format (sAMAccountName only).
            $sessionStates = @{}
            foreach ($row in $script:sdDataTable.Rows) {
                $u = [string]$row['User']
                if ($u -match '\\') { $u = $u.Split('\')[-1] }
                elseif ($u -match '@') { $u = $u.Split('@')[0] }
                $h = [string]$row['Session Host']
                if ($u -and $u -ne '-' -and $h -and $h -ne '-') {
                    $sessionStates["$($u.ToLower())|$($h.ToLower())"] = [string]$row['State']
                }
            }

            # --- Populate DataTable directly from the combined response ---
            # Because the fullouter join already merged lock + session data server-side,
            # we can iterate the single result set and build rows directly. No
            # client-side merge/hashtable step is needed (unlike the old two-query
            # approach which required merging two separate response sets).
            foreach ($r in $resp.tables[0].rows) {
                $user_ = if ($iUser -ge 0) { [string]$r[$iUser] } else { '' }
                $host_ = if ($iHost -ge 0) { [string]$r[$iHost] } else { '' }
                $lockState = if ($iLS -ge 0 -and $r[$iLS]) { [string]$r[$iLS] } else { '-' }

                # Map the numeric disconnect reason code to a human-readable label.
                # The code comes from EventID 40's RenderedDescription field.
                $reasonCode = if ($iDReason -ge 0 -and $r[$iDReason]) { [string]$r[$iDReason] } else { '' }
                $discType = & $mapReason $reasonCode

                # Look up the live session state from the parent DataTable.
                # If the user has no active session, show "No Session" and also
                # override Lock State to "No Session" (a lock state is meaningless
                # without an active session to associate it with).
                $stateKey = "$($user_.ToLower())|$($host_.ToLower())"
                $sessionState = if ($sessionStates.ContainsKey($stateKey)) { $sessionStates[$stateKey] } else { 'No Session' }

                $dr = $dt.NewRow()
                $dr["User"]            = $user_
                $dr["Session Host"]    = $host_
                $dr["Lock State"]      = if ($sessionState -ne 'No Session') { $lockState } else { 'No Session' }
                $dr["Session State"]   = $sessionState
                $dr["Last Lock"]       = (& $fmtTime $r $iLock)
                $dr["Last Unlock"]     = (& $fmtTime $r $iUnlck)
                $dr["Last Logon"]      = (& $fmtTime $r $iLogon)
                $dr["Last Logoff"]     = (& $fmtTime $r $iLogoff)
                $dr["Last Disconnect"] = (& $fmtTime $r $iDisc)
                $dr["Disconnect Type"] = $discType
                $dr["Last Reconnect"]  = (& $fmtTime $r $iRecon)
                [void]$dt.Rows.Add($dr)
            }

            # --- Preserve and restore sort/filter state across data refreshes ---
            # When ItemsSource is replaced, WPF resets the DataGrid's sort and
            # filter state. We save the current SortDescriptions before swapping,
            # then reapply them after. This ensures the user's chosen sort order
            # and column header arrows persist through auto-refresh cycles.
            $savedSort = @()
            if ($script:_advGrid.Items -and $script:_advGrid.Items.SortDescriptions.Count -gt 0) {
                foreach ($sd in $script:_advGrid.Items.SortDescriptions) {
                    $savedSort += [System.ComponentModel.SortDescription]::new($sd.PropertyName, $sd.Direction)
                }
            }

            # Bind the new DataTable to the DataGrid via its DefaultView
            $script:_advGrid.ItemsSource = $dt.DefaultView

            # Restore sort descriptions and column header arrows
            if ($savedSort.Count -gt 0) {
                $script:_advGrid.Items.SortDescriptions.Clear()
                foreach ($sd in $savedSort) { $script:_advGrid.Items.SortDescriptions.Add($sd) }
                foreach ($col in $script:_advGrid.Columns) {
                    $match = $savedSort | Where-Object { $_.PropertyName -eq $col.SortMemberPath }
                    if ($match) { $col.SortDirection = $match.Direction } else { $col.SortDirection = $null }
                }
            }

            # Restore the text filter if the user had typed something in the filter box.
            # The RowFilter uses DataTable expression syntax (not regex). Special chars
            # are escaped to prevent expression injection.
            $filterText = if ($script:_advFilterBox) { $script:_advFilterBox.Text.Trim() } else { '' }
            if ($filterText -ne '') {
                $escaped = $filterText.Replace("'", "''").Replace("*", "[*]").Replace("%", "[%]")
                $script:_advGrid.ItemsSource.RowFilter = "User LIKE '%$escaped%' OR [Session Host] LIKE '%$escaped%'"
            }

            $now = Get-Date -Format 'HH:mm:ss'
            $script:_advStatus.Text = "$($dt.Rows.Count) row(s)  |  Updated: $now"
            $script:_shExportCsv.IsEnabled = $true
            if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] Displayed $($dt.Rows.Count) row(s)`r`n") } catch {} }
        } else {
            $selLabel = if ($script:_advDatePicker -and $script:_advDatePicker.SelectedDate) { $script:_advDatePicker.SelectedDate.ToString('yyyy-MM-dd') } else { 'today' }
            $script:_advStatus.Text = "No events found for $selLabel."
            $script:_shExportCsv.IsEnabled = $false
            if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] No events found`r`n") } catch {} }
        }
    } catch {
        $script:_advStatus.Text = "Error querying Log Analytics: $_"
        if ($script:LogFile) { try { [IO.File]::AppendAllText($script:LogFile, "[$(Get-Date -Format 'HH:mm:ss')] [SessionHistory] ERROR: $_`r`n") } catch {} }
    }

    # Reset countdown for next auto-refresh
    $script:_advNextRefresh = [DateTime]::Now.AddSeconds($script:RefreshIntervalSeconds)
}

